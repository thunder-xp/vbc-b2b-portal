const dictionaries = { ru, ro } satisfies Record<
  PartnerLocale,
  Record<PartnerTranslationKey, string>
>;

export function partnerText(
  locale: PartnerLocale,
  key: PartnerTranslationKey,
): string {
  const value = dictionaries[locale][key];
  if (value) return value;
  if (process.env.NODE_ENV !== "production") {
    console.warn(`[partner-i18n] Missing ${locale} translation: ${key}`);
  }
  return dictionaries.ru[key];
}

export function partnerDictionary(
  locale: PartnerLocale,
): Readonly<Record<PartnerTranslationKey, string>> {
  return dictionaries[locale];
}
